create table color (
    id integer generated by default as identity,
    hex varchar(7),
    code varchar(20) not null,
    name varchar(50) not null,
    primary key (id),
    constraint uk_color_code unique (code),
    constraint uk_color_name unique (name)
);

create table image (
    id bigint generated by default as identity,
    storage_key varchar(500) not null,
    original_filename varchar(255),
    content_type varchar(100) not null,
    size_bytes bigint not null,
    checksum varchar(64),
    width integer,
    height integer,
    alt_text varchar(500),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    primary key (id),
    constraint uk_image_storage_key unique (storage_key),
    constraint uk_image_checksum unique (checksum)
);

create table product (
    id integer generated by default as identity,
    name varchar(255),
    description TEXT,
    gender varchar(255) check (gender in ('MAN','WOMAN','UNISEX')),
    season varchar(255) check (season in ('SUMMER','WINTER','DEMI_SEASON','ALL_SEASON')),
    base_price numeric(10,2),
    primary key (id),
    constraint uk_product_name unique (name)
);

create table product_image (
    id bigint generated by default as identity,
    product_id integer not null,
    image_id bigint not null,
    sort_order integer default 0 not null,
    is_main boolean default false not null,
    alt_text varchar(500),
    primary key (id),
    constraint uk_product_image unique (product_id, image_id)
);

create table product_textile (
    id integer generated by default as identity,
    product_id integer not null,
    textile_id integer not null,
    percentage integer,
    primary_fabric boolean,
    primary key (id),
    constraint uk_product_textile unique (product_id, textile_id)
);

create table product_variant (
    id integer generated by default as identity,
    product_id integer not null,
    color_id integer,
    size_id integer,
    sku varchar(50) not null,
    barcode varchar(50),
    stock_quantity integer not null,
    price numeric(10,2),
    primary key (id),
    constraint uk_product_variant_sku unique (sku),
    constraint uk_product_variant_barcode unique (barcode),
    constraint uk_product_variant_product_color_size unique (product_id, color_id, size_id)
);

create table product_variant_image (
    id bigint generated by default as identity,
    variant_id integer not null,
    image_id bigint not null,
    sort_order integer not null,
    is_main boolean not null,
    alt_text varchar(500),
    primary key (id),
    constraint uk_product_variant_image unique (variant_id, image_id)
);

create table size (
    id integer generated by default as identity,
    code varchar(20) not null,
    system varchar(20) not null check (system in ('LETTER','EU','US','UK','KIDS','SHOES')),
    label varchar(100),
    sort_order integer not null,
    primary key (id),
    constraint uk_size_system_code unique (system, code)
);

create table textile (
    id integer generated by default as identity,
    name varchar(100) not null,
    description varchar(1000),
    composition varchar(255),
    density_gsm integer,
    weave_type varchar(30) check (weave_type in ('WOVEN','KNITTED','NON_WOVEN','LACE','FELT')),
    stretch varchar(20) check (stretch in ('NONE','LOW','MEDIUM','HIGH')),
    manufacturer varchar(20) check (manufacturer in ('RUSSIA','CHINA','TURKEY','BELARUS')),
    care_instructions varchar(500),
    price_modifier numeric(10,2),
    active boolean not null,
    primary key (id),
    constraint uk_textile_name unique (name)
);

create table users (
    id bigint generated by default as identity,
    email varchar(100) not null,
    password varchar(255) not null,
    role varchar(20) not null check (role in ('USER','ADMIN')),
    first_name varchar(50),
    last_name varchar(50),
    phone varchar(20),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone,
    primary key (id),
    constraint uk_users_email unique (email)
);

alter table if exists product_image
    add constraint fk_product_image_image foreign key (image_id) references image;
alter table if exists product_image
    add constraint fk_product_image_product foreign key (product_id) references product;

alter table if exists product_textile
    add constraint fk_product_textile_product foreign key (product_id) references product;
alter table if exists product_textile
    add constraint fk_product_textile_textile foreign key (textile_id) references textile;

alter table if exists product_variant
    add constraint fk_product_variant_color foreign key (color_id) references color;
alter table if exists product_variant
    add constraint fk_product_variant_product foreign key (product_id) references product;
alter table if exists product_variant
    add constraint fk_product_variant_size foreign key (size_id) references size;

alter table if exists product_variant_image
    add constraint fk_product_variant_image_image foreign key (image_id) references image;
alter table if exists product_variant_image
    add constraint fk_product_variant_image_variant foreign key (variant_id) references product_variant;