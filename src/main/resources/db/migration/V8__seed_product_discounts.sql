-- Товары со скидкой логично показывать в категории Sale.
-- is_primary = true ставим только тем товарам, у которых ещё нет ни одной
-- категории (товары 6+ в V5 не разложены по категориям).
INSERT INTO product_category (product_id, category_id, sort_order, is_primary)
SELECT p.id,
       c.id,
       0,
       NOT EXISTS (SELECT 1 FROM product_category pc WHERE pc.product_id = p.id)
FROM product p
JOIN category c ON c.slug = 'sale'
WHERE p.discounted_price IS NOT NULL
  AND p.discounted_price < p.base_price
ON CONFLICT DO NOTHING;
